"""Python str.lower() 표를 전 코드 포인트(서로게이트 제외)에 대해 만든다 (위험 R2).

출력: rust_app/tests/data/py_lower_table.txt
  L <cp hex> <lower cp hex>[,<lower cp hex>...]   chr(cp).lower() != chr(cp) 인 코드 포인트
  S <class> <start hex> <end hex>                  Final_Sigma 판단에서의 글자 분류 구간
     class: I = case-ignorable(건너뜀), C = cased 이고 ignorable 아님, (나머지는 기록 안 함)

분류는 Python 내부 표(_PyUnicode_IsCased / _PyUnicode_IsCaseIgnorable)를 직접 볼 수 없어서
handle_capital_sigma 의 결과를 관찰해 유도한다.
  P1 = (c + "Σ").lower() 가 ς 로 끝남  <=> cased(c) and not ignorable(c)
  P2 = ("A" + c + "Σ").lower() 가 ς 로 끝남 <=> ignorable(c) or cased(c)
  => C: P1,  I: P2 and not P1,  기타: not P2
ignorable 인 글자는 cased 여부와 상관없이 항상 건너뛰므로 세 분류로 충분하다.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "rust_app" / "tests" / "data" / "py_lower_table.txt"


def classify(c: str) -> str:
    p1 = (c + "Σ").lower().endswith("ς")
    p2 = ("A" + c + "Σ").lower().endswith("ς")
    if p1:
        return "C"
    if p2:
        return "I"
    return "-"


def main() -> int:
    lines = [
        f"# generated by verify/gen_lower_table.py, Python {sys.version.split()[0]}, "
        f"Unicode {unicodedata.unidata_version}"
    ]
    n_lower = 0
    runs: list[tuple[str, int, int]] = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        low = c.lower()
        if low != c:
            lines.append("L %X %s" % (cp, ",".join("%X" % ord(x) for x in low)))
            n_lower += 1
        cls = classify(c)
        if runs and runs[-1][0] == cls and runs[-1][2] == cp - 1:
            runs[-1] = (cls, runs[-1][1], cp)
        elif runs and runs[-1][0] == cls and runs[-1][2] == 0xD7FF and cp == 0xE000:
            # 서로게이트 구간을 건너 이어지는 경우는 따로 구간을 만든다(단순화)
            runs.append((cls, cp, cp))
        else:
            runs.append((cls, cp, cp))
    n_runs = 0
    for cls, start, end in runs:
        if cls != "-":
            lines.append("S %s %X %X" % (cls, start, end))
            n_runs += 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {n_lower} lower mappings, {n_runs} sigma-class runs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
