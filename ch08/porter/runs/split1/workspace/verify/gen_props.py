"""Python 3.12 의 공백 집합(str.split 기준)과 re 의 \\d 집합을 전 코드 포인트에서 뽑는다 (위험 R1, R4).

출력: rust_app/tests/data/py_props.txt
  SPACE <start hex> <end hex>   "a{c}b".split() 가 두 조각이 되는 글자 구간
  DIGIT <start hex> <end hex>   re.fullmatch(r"\\d", c) 가 맞는 글자 구간 (argparse 음수 판별 정규식)
표준 출력에는 Rust 소스에 붙일 수 있는 구간 목록을 쓴다.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "rust_app" / "tests" / "data" / "py_props.txt"


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if pred(chr(cp)):
            if out and out[-1][1] == cp - 1:
                out[-1] = (out[-1][0], cp)
            else:
                out.append((cp, cp))
    return out


def main() -> int:
    space = ranges(lambda c: ("a" + c + "b").split() == ["a", "b"])
    space_isspace = ranges(str.isspace)
    assert space == space_isspace, "split() and isspace() disagree"
    digit_re = re.compile(r"\d")
    digit = ranges(lambda c: digit_re.fullmatch(c) is not None)
    lines = ["# generated by verify/gen_props.py, Python " + sys.version.split()[0]]
    lines += ["SPACE %X %X" % r for r in space]
    lines += ["DIGIT %X %X" % r for r in digit]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("SPACE:", ", ".join("(0x%X, 0x%X)" % r for r in space))
    print("DIGIT:", ", ".join("(0x%X, 0x%X)" % r for r in digit))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(space)} space ranges, {len(digit)} digit ranges")
    return 0


if __name__ == "__main__":
    sys.exit(main())
