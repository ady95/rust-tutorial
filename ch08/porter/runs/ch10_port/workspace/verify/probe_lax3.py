from __future__ import annotations

from probe_lax import INT, run

NINES = "9" * 20
CASES = {
    "0*4290+9*20": "0" * 4290 + NINES,
    "0*4281+9*20": "0" * 4281 + NINES,
    "0*4280+9*20": "0" * 4280 + NINES,
    "-+0*4300+5": "-" + "0" * 4300 + "5",
    "+1*4301": "+" + "1" * 4301,
    "+1*4300": "+" + "1" * 4300,
    "1_*100+1*4200": "1_" * 100 + "1" * 4200,
    "1_*100+1*4201": "1_" * 100 + "1" * 4201,
    "-1*4299+.0": "-" + "1" * 4299 + ".0",
    "-1*4300+.0": "-" + "1" * 4300 + ".0",
    "1*4301+.0": "1" * 4301 + ".0",
    "-0*4280+9*20": "-" + "0" * 4280 + NINES,
    "-0*4279+9*20": "-" + "0" * 4279 + NINES,
    "1*4300+.0*3000": "1" * 4300 + "." + "0" * 3000,
    "-1*4299": "-" + "1" * 4299,
    "-1_*10+1*4290": "-" + "1_" * 10 + "1" * 4290,
    "-1_*10+1*4289": "-" + "1_" * 10 + "1" * 4289,
    "1*4301 with x": "1" * 4300 + "x",
    "x*4301": "x" * 4301,
    "1*4301+_": "1" * 4301 + "_",
    "1*20+x": "1" * 20 + "x",
}


def main() -> None:
    for label, s in CASES.items():
        print(f"{label:>18} len={len(s)}: {run(INT, s)[:40]}")


if __name__ == "__main__":
    main()
