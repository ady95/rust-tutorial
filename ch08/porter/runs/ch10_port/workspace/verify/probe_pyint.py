"""Python int() 의 4300자리 제한 동작 실측(pydantic 이 int() 를 쓰는지 판단용).

사용법: python3 verify/probe_pyint.py
"""

CASES = {
    "0+1*4304": "0" + "1" * 4304, "1*4301+5+9": "1" * 4301 + "5+9", "1*4301": "1" * 4301, "-1*4300": "-" + "1" * 4300,
    "+1*4301": "+" + "1" * 4301, "1_*100+1*4201": "1_" * 100 + "1" * 4201, "9*4301+5_5": "9" * 4301 + "5_5",
    "1*4301-_": "1" * 4301 + "-_", "1*4300x": "1" * 4300 + "x", "0*4290+9*20": "0" * 4290 + "9" * 20,
    "1*4301_": "1" * 4301 + "_", "-1_*10+1*4290": "-" + "1_" * 10 + "1" * 4290,
}

for label, s in CASES.items():
    try:
        int(s)
        print(label, "OK")
    except ValueError as err:
        print(label, str(err)[:60])
