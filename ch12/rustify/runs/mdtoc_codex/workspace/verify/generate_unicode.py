"""Generate Python Unicode semantics for the standard-library-only Rust port."""
from pathlib import Path
import re

def ranges(values):
    out=[]
    for x in values:
        if out and out[-1][1]+1==x: out[-1]=(out[-1][0],x)
        else: out.append((x,x))
    return out

def generate():
    word=[]; space=[]; cased=[]; ignorable=[]; lower=[]; decimal=[]
    for n in range(0x110000):
        if 0xD800<=n<=0xDFFF: continue
        c=chr(n)
        if c.isdecimal(): decimal.append((n,int(c)))
        if re.fullmatch(r'\w',c): word.append(n)
        if c.isspace(): space.append(n)
        if c.islower() or c.isupper() or c.istitle(): cased.append(n)
        if ('AΣ'+c+'A').lower()[1]=='σ' and (' '+c+'Σ').lower()[-1]!='ς': ignorable.append(n)
        if c.lower()!=c:
            lower.append((n,c.lower()))
    out=['// Generated by verify/generate_unicode.py; Python Unicode semantics.']
    for name, vals in [('WORD',word),('SPACE',space),('CASED',cased),('IGNORABLE',ignorable)]:
        out.append('pub const '+name+': &[(u32,u32)] = &'+repr(ranges(vals)).replace('[','[').replace(']',']')+';')
    out.append('pub const DECIMAL: &[(u32,u32)] = &'+repr(decimal)+';')
    out.append('pub const LOWER: &[(u32,&str)] = &[')
    for n,s in lower:
        out.append('('+str(n)+',"'+''.join('\\u{'+format(ord(c),'x')+'}' for c in s)+'"),')
    out.append('];')
    return '\n'.join(out)+'\n'
if __name__=='__main__':
    Path('rust_app/src/unicode.rs').write_text(generate())
